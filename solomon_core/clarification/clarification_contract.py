# Clarification Subsystem Contract
# ---------------------------------------------------------------------------
#
# PURPOSE:
#   Define the input and output schema for the clarification subsystem.
#
# AUTHORITY:
#   • Pure data structures
#   • No logic
#   • No inference
#   • No dependencies on other subsystems
#
# DESIGN:
#   • Deterministic
#   • Stable
#   • Explicit
# ---------------------------------------------------------------------------

from dataclasses import dataclass
from typing import List, Optional


# ===========================================================================
# Input Contract
# ===========================================================================

@dataclass(frozen=True)
class ClarificationRequest:
    """
    Input to the clarification subsystem.

    FIELDS:
    • user_query:
        The raw user input string.

    • ambiguity_type:
        A controlled string describing the ambiguity class.
        Examples (non-exhaustive):
            - "web_vs_explanation"
            - "reference_resolution"
            - "multi_intent"
            - "unknown"

    • context:
        Optional contextual string.
        Must NOT include system-internal state or routing decisions.
    """

    user_query: str
    ambiguity_type: str
    context: Optional[str] = None


# ===========================================================================
# Output Contract (Phase 99 Unified UX)
# ===========================================================================

@dataclass(frozen=True)
class ClarificationResponse:
    """
    Output from the clarification subsystem.

    FIELDS:
    • answer:
        The clarification question generated by the LLM.

    • bridge:
        A single conversational bridge sentence introducing next steps.

    • suggestions:
        List of short UI chip strings (3–5 items).
    """

    answer: str
    bridge: str
    suggestions: List[str]


__all__ = [
    "ClarificationRequest",
    "ClarificationResponse",
]