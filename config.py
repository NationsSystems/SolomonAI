def _build_redis_session_client():
    try:
        from redis import Redis
    except ImportError as exc:
        raise RuntimeError('Redis session storage requires the redis package.') from exc
    return Redis.from_url(settings.REDIS_URL, socket_connect_timeout=settings.SESSION_REDIS_CONNECT_TIMEOUT_SECONDS, socket_timeout=settings.SESSION_REDIS_SOCKET_TIMEOUT_SECONDS, socket_keepalive=True, health_check_interval=30, max_connections=settings.SESSION_REDIS_MAX_CONNECTIONS, decode_responses=False)

def init_flask_config(app):
    validate_runtime_settings()
    app.secret_key = settings.SECRET_KEY
    session_config = {'SECRET_KEY': settings.SECRET_KEY, 'SESSION_TYPE': settings.SESSION_TYPE, 'SESSION_COOKIE_NAME': settings.SESSION_COOKIE_NAME, 'SESSION_KEY_PREFIX': settings.SESSION_KEY_PREFIX, 'SESSION_PERMANENT': True, 'SESSION_ID_LENGTH': 32, 'SESSION_SERIALIZATION_FORMAT': 'msgpack', 'SESSION_REFRESH_EACH_REQUEST': False, 'PERMANENT_SESSION_LIFETIME': timedelta(minutes=settings.SESSION_LIFETIME_MINUTES), 'SESSION_COOKIE_SAMESITE': settings.SESSION_COOKIE_SAMESITE, 'SESSION_COOKIE_HTTPONLY': True, 'SESSION_COOKIE_SECURE': settings.SESSION_COOKIE_SECURE, 'MAX_CONTENT_LENGTH': settings.MAX_REQUEST_BODY_BYTES, 'PREFERRED_URL_SCHEME': 'https' if settings.SESSION_COOKIE_SECURE else 'http'}
    if settings.SESSION_TYPE == 'redis':
        session_config['SESSION_REDIS'] = _build_redis_session_client()
    else:
        session_config['SESSION_FILE_DIR'] = settings.SESSION_FILE_DIR
        session_config['SESSION_FILE_THRESHOLD'] = settings.SESSION_FILE_THRESHOLD
        os.makedirs(settings.SESSION_FILE_DIR, exist_ok=True)
    app.config.update(session_config)
